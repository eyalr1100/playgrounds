/* PostGIS Quest chapter 1: tables and rows. No SQL is assumed: SELECT, *, FROM, columns, WHERE with text and numbers,
   ORDER BY, DESC, LIMIT and count(*). Every check reads the query just run. DOM-free. */
(()=>{
'use strict';
const PQ=globalThis.PQ=globalThis.PQ||{};
const need=PQ.need;
PQ.CH.push({
  name:'Tables and rows',badge:'Harbor Ledger',
  story:'A note pinned up in the harbor office says Odile Marrow kept the whole island in a database. Learn to read its tables, and find where her trail begins.',
  intro:'Odile Marrow, Gullhaven\'s old mapmaker, sailed away and left a note in the harbor office: <i>"Every place on this island is in my database. My Compass Rose lies where my stones gather thickest."</i> A database keeps its facts in <b>tables</b>, and you ask it questions in a language called <b>SQL</b>. This chapter teaches the first questions: show a table, pick columns, keep some rows, sort them and count them.',
  learned:['SELECT * FROM places','SELECT name, kind FROM places',"WHERE kind = 'harbor'",'ORDER BY depth_m DESC','LIMIT 1','count(*)'],
  missions:[
  {title:'Look at a whole table',
   goal:'Odile\'s database has a table called <code>places</code>. Show all of it, every row and every column: type <code>SELECT * FROM places;</code> and press Run.',
   anat:[['SELECT','kw','show me'],['*','op','every column'],['FROM','kw','from the table'],['places','tbl','the table']],
   how:['<code>SELECT * FROM places;</code> asks the database for every row of the table <code>places</code>, with all of its columns.',
     '<code>SELECT</code> starts the question. It means "show me".',
     '<code>*</code> stands for every column, so you do not have to name them.',
     '<code>FROM places</code> says which table to read. The <code>;</code> ends the query.',
     'The rows appear under the editor, and the map shows where each place is.'],
   explain:'A table is like a spreadsheet: each row is one thing (here, one place on the island) and each column is one fact about it. The last column, <code>geom</code>, holds the place\'s location. It looks like a long code for now; chapter 2 learns to read it.',
   hint:'Type exactly <code>SELECT * FROM places;</code> and press Run, or <kbd>Ctrl</kbd>+<kbd>Enter</kbd>.',
   answer:'SELECT * FROM places;',
   wrong:['SELECT name FROM places;','SELECT * FROM wells;'],
   check:need({reads:['places'],has:['star'],tip:'Show every column of <code>places</code>, with nothing left out: <code>SELECT * FROM places;</code>'})},

  {title:'Pick the columns',
   goal:'You only need two facts about each place: its <code>name</code> and its <code>kind</code>. Show just those two columns of <code>places</code>.',
   anat:[['SELECT','kw','show me'],['name, kind','col','these columns'],['FROM','kw','from the table'],['places','tbl','the table']],
   how:['<code>SELECT name, kind FROM places;</code> shows every row of <code>places</code>, but only the columns <code>name</code> and <code>kind</code>.',
     'In place of <code>*</code>, you list the columns you want after <code>SELECT</code>.',
     'A comma separates them, and they come out in the order you list them.',
     'Every row is still there: picking columns never removes rows.'],
   explain:'Column names are written without quotes. If you misspell one, the database says <code>column "nme" does not exist</code> and points at it with <code>^</code>.',
   hint:'<code>SELECT name, kind FROM places;</code>',
   answer:'SELECT name, kind FROM places;',
   wrong:['SELECT * FROM places;','SELECT name FROM places;','SELECT name, kind FROM wells;'],
   check:need({reads:['places'],extra:c=>c.cols.length===2||'Show exactly two columns: <code>name</code> and <code>kind</code>.'})},

  {title:'Keep only some rows',
   goal:'Odile\'s note says her trail starts "where the boats come in". Show the <code>name</code> of every place whose <code>kind</code> is <code>harbor</code>.',
   anat:[['SELECT','kw'],['name','col'],['FROM','kw'],['places','tbl'],['WHERE','kw','keep only rows where'],['kind','col'],['=','op','equals'],["'harbor'",'val','a piece of text']],
   how:['<code>SELECT name FROM places WHERE kind = \'harbor\';</code> shows the names of the places whose kind is harbor, and no others.',
     '<code>WHERE</code> keeps only the rows where the condition after it is true.',
     '<code>kind = \'harbor\'</code> is the condition: the <code>kind</code> column equals the text <code>harbor</code>.',
     'Text goes in single quotes <code>\'...\'</code>, so the database knows it is a value and not a column name.'],
   explain:'Without the quotes, <code>harbor</code> would be read as a column name, and the database would say <code>column "harbor" does not exist</code>. Text must match exactly: <code>\'Harbor\'</code> with a capital H is different text.',
   hint:'<code>SELECT name FROM places WHERE kind = \'harbor\';</code>',
   answer:"SELECT name FROM places WHERE kind = 'harbor';",
   wrong:['SELECT name FROM places;',"SELECT name FROM places WHERE name = 'Harbor';","SELECT 'Harbor';"],
   check:need({reads:['places'],has:['where'],extra:c=>c.refs('kind')||'Keep the rows by their <code>kind</code>: <code>WHERE kind = \'harbor\'</code>.'})},

  {title:'Sort the rows',
   goal:'The table <code>wells</code> lists the island\'s wells with their depth in metres, <code>depth_m</code>. Show each well\'s <code>name</code> and <code>depth_m</code>, shallowest first.',
   anat:[['SELECT','kw'],['name, depth_m','col'],['FROM','kw'],['wells','tbl'],['ORDER BY','kw','sort by'],['depth_m','col','smallest first']],
   how:['<code>SELECT name, depth_m FROM wells ORDER BY depth_m;</code> lists every well with its depth, the shallowest at the top.',
     '<code>ORDER BY</code> sorts the rows by the column after it.',
     'Numbers sort from small to large unless you say otherwise.',
     'Without <code>ORDER BY</code>, the database may give rows in any order it likes.'],
   explain:'A database promises an order only when you ask for one. Today the rows may come out in the order they were stored, but that is luck, not a rule.',
   hint:'<code>SELECT name, depth_m FROM wells ORDER BY depth_m;</code>',
   answer:'SELECT name, depth_m FROM wells ORDER BY depth_m;',
   wrong:['SELECT name, depth_m FROM wells;','SELECT name, depth_m FROM wells ORDER BY depth_m DESC;','SELECT name, depth_m FROM wells ORDER BY name;'],
   check:need({reads:['wells'],has:['order'],ordered:true,tip:'Sort by <code>depth_m</code>, with the shallowest well first.'})},

  {title:'The deepest well',
   goal:'Captain Brack, the harbor master, swears Odile hid something in the deepest well. Show the <code>name</code> and <code>depth_m</code> of the one deepest well, and only that row.',
   anat:[['ORDER BY','kw','sort by'],['depth_m','col'],['DESC','kw','largest first'],['LIMIT','kw','keep only'],['1','val','one row']],
   how:['<code>SELECT name, depth_m FROM wells ORDER BY depth_m DESC LIMIT 1;</code> sorts the wells deepest first and keeps only the top row.',
     '<code>DESC</code> (descending) turns the sort around: largest first.',
     '<code>LIMIT 1</code> keeps only the first row of the sorted result.',
     'Together they answer "which is the biggest?" in one line.'],
   explain:'<code>LIMIT</code> without <code>ORDER BY</code> keeps "some" rows, not the right ones. Always sort first when you ask for the top of a list.',
   hint:'Sort with <code>ORDER BY depth_m DESC</code>, then add <code>LIMIT 1</code>.',
   answer:'SELECT name, depth_m FROM wells ORDER BY depth_m DESC LIMIT 1;',
   wrong:['SELECT name, depth_m FROM wells ORDER BY depth_m LIMIT 1;','SELECT name, depth_m FROM wells LIMIT 1;','SELECT name, depth_m FROM wells ORDER BY depth_m DESC;'],
   check:need({reads:['wells'],has:['order','limit'],tip:'Sort the deepest first with <code>DESC</code>, and keep one row with <code>LIMIT 1</code>.'})},

  {title:'Count the rows',
   goal:'The Hilltop Well was empty: the Captain was wrong. Odile\'s note says to "count the deep ones". How many wells are deeper than 10 metres? Show the count.',
   anat:[['SELECT','kw'],['count(*)','fn','how many rows'],['FROM','kw'],['wells','tbl'],['WHERE','kw'],['depth_m','col'],['>','op','greater than'],['10','val','a number']],
   how:['<code>SELECT count(*) FROM wells WHERE depth_m > 10;</code> counts the wells deeper than 10 metres and shows one number.',
     '<code>WHERE depth_m > 10</code> keeps only the rows whose depth is greater than 10. Numbers need no quotes.',
     '<code>count(*)</code> is a <b>function</b>: a named calculation with its input in brackets. This one counts the rows that are left.',
     'The answer is one row with one column, called <code>count</code>.'],
   explain:'<code>count(*)</code> squeezes all the rows into one number. The other comparisons work the same way: <code>&lt;</code> less than, <code>&gt;=</code> at least, <code>&lt;=</code> at most.',
   hint:'<code>SELECT count(*) FROM wells WHERE depth_m > 10;</code>',
   answer:'SELECT count(*) FROM wells WHERE depth_m > 10;',
   wrong:['SELECT count(*) FROM wells;','SELECT 4;','SELECT count(*) FROM wells WHERE depth_m < 10;','SELECT name FROM wells WHERE depth_m > 10;'],
   check:need({reads:['wells'],calls:['count'],has:['where']})},
  ]});
})();
